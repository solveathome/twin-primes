function primesUpTo(n) {
  const c = new Uint8Array(n + 1), out = [];
  for (let i = 2; i <= n; i++) { if (!c[i]) { out.push(i); for (let j = i * i; j <= n; j += i) c[j] = 1; } }
  return out;
}

// ---- level construction, identical to natal-cap-39-triple-census.js -------
function level(x) {
  const basePs = primesUpTo(x).filter(p => p >= 7);
  const W = 30 * basePs.reduce((a, b) => a * b, 1);
  const A = new Uint8Array(W);
  for (let r = 11; r < W; r += 30) A[r] = 1;
  for (let r = 17; r < W; r += 30) A[r] = 1;
  for (const p of basePs) { for (let j = 0; j < W; j += p) A[j] = 0; for (let j = p - 2; j < W; j += p) A[j] = 0; }
  let N = 0; for (let r = 0; r < W; r++) if (A[r]) N++;
  const qs = primesUpTo(Math.floor(Math.sqrt(W)) + 1).filter(q => q > x && q * q <= W);
  return { x, W, A, N, qs, K: qs.length, lnW: Math.log(W) };
}

// deterministic 32-bit mixing, so the run is reproducible
function mix(a) { a |= 0; a = (a ^ 61) ^ (a >>> 16); a = (a + (a << 3)) | 0; a ^= a >>> 4; a = Math.imul(a, 0x27d4eb2d); a ^= a >>> 15; return a >>> 0; }


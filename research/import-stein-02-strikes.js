// ==========================================================================
// b3, EXACTLY, BY SIGNATURE CELLS
// ==========================================================================
function b3exact(e) {
  const { W, A, N, qs, K } = e.L;
  const t0 = Date.now();
  // natal index
  const idx = new Int32Array(W).fill(-1);
  const nat = new Int32Array(N);
  { let k = 0; for (let r = 0; r < W; r++) if (A[r]) { idx[r] = k; nat[k] = r; k++; } }
  // per-prime, per-side random tags
  const R1 = new Uint32Array(2 * K), R2 = new Uint32Array(2 * K);
  for (let i = 0; i < K; i++) { R1[2 * i] = mix(qs[i] * 2 + 1); R2[2 * i] = mix(qs[i] * 2 + 1 + 0x9e3779b9); R1[2 * i + 1] = mix(qs[i] * 2 + 2); R2[2 * i + 1] = mix(qs[i] * 2 + 2 + 0x9e3779b9); }
  // signature hashes
  const h1 = new Uint32Array(N), h2 = new Uint32Array(N);
  const nq = new Float64Array(K);              // #{r in N struck by q, either side}
  for (let i = 0; i < K; i++) {
    const q = qs[i], r1L = R1[2 * i], r2L = R2[2 * i], r1R = R1[2 * i + 1], r2R = R2[2 * i + 1];
    let c = 0;
    for (let j = 0; j < W; j += q) { const k = idx[j]; if (k >= 0) { h1[k] ^= r1L; h2[k] ^= r2L; c++; } }
    for (let j = q - 2; j < W; j += q) { const k = idx[j]; if (k >= 0) { h1[k] ^= r1R; h2[k] ^= r2R; c++; } }
    nq[i] = c;
  }
  // class counts: 53-bit key, sorted
  const SH = 2097152;                          // 2^21
  const keys = new Float64Array(N);
  for (let k = 0; k < N; k++) keys[k] = h1[k] * SH + (h2[k] >>> 11);
  const sk = Float64Array.from(keys); sk.sort();
  const uk = new Float64Array(N), uc = new Float64Array(N);
  let U = 0;
  for (let k = 0; k < N;) { let j = k; while (j < N && sk[j] === sk[k]) j++; uk[U] = sk[k]; uc[U] = j - k; U++; k = j; }
  function lookup(key) {
    let lo = 0, hi = U - 1;
    while (lo <= hi) { const m = (lo + hi) >> 1; if (uk[m] === key) return uc[m]; if (uk[m] < key) lo = m + 1; else hi = m - 1; }
    return 0;
  }
  // per prime, enumerate the sigma cells that have a q-sibling
  let b3 = 0, cellsSeen = 0;
  const buf1 = new Uint32Array(1 << 16), buf2 = new Uint32Array(1 << 16);
  const skey = new Float64Array(1 << 16);
  let cap = 1 << 16;
  let sb1 = buf1, sb2 = buf2, sbk = skey;
  for (let i = 0; i < K; i++) {
    const q = qs[i], n = nq[i];
    if (n === 0) { b3 += 2 * (1 / q) * (N) / N; continue; }
    if (n > cap) { cap = 1 << Math.ceil(Math.log2(n + 1)); sb1 = new Uint32Array(cap); sb2 = new Uint32Array(cap); sbk = new Float64Array(cap); }
    const r1L = R1[2 * i], r2L = R2[2 * i], r1R = R1[2 * i + 1], r2R = R2[2 * i + 1];
    let m = 0;
    for (let j = 0; j < W; j += q) { const k = idx[j]; if (k >= 0) { sb1[m] = h1[k] ^ r1L; sb2[m] = h2[k] ^ r2L; m++; } }
    for (let j = q - 2; j < W; j += q) { const k = idx[j]; if (k >= 0) { sb1[m] = h1[k] ^ r1R; sb2[m] = h2[k] ^ r2R; m++; } }
    for (let z = 0; z < m; z++) sbk[z] = sb1[z] * SH + (sb2[z] >>> 11);
    const ord = new Float64Array(m); for (let z = 0; z < m; z++) ord[z] = sbk[z];
    ord.sort();
    let baseSum = 0, accL = 0, accR = 0;
    for (let z = 0; z < m;) {
      let w = z; while (w < m && ord[w] === ord[z]) w++;
      const sig = ord[z];
      // find the raw (h1,h2) for this sigma: recover from the first member
      let s1 = 0, s2 = 0;
      for (let t = 0; t < m; t++) if (sbk[t] === sig) { s1 = sb1[t]; s2 = sb2[t]; break; }
      const nsig = lookup(sig);
      const nL = lookup((s1 ^ r1L) * SH + ((s2 ^ r2L) >>> 11));
      const nR = lookup((s1 ^ r1R) * SH + ((s2 ^ r2R) >>> 11));
      const cell = nsig + nL + nR;
      accL += Math.abs(nL - cell / q);
      accR += Math.abs(nR - cell / q);
      baseSum += nsig;
      cellsSeen++;
      z = w;
    }
    // cells with no q-sibling: contribution (1/q) n(sigma) each, closed form
    const rest = N - n - baseSum;
    b3 += (accL + accR + 2 * rest / q) / N;
  }
  return { b3, cellsSeen, classes: U, secs: (Date.now() - t0) / 1000 };
}

// ==========================================================================
// C2b — THE DECOMPOSITION THAT DECIDES WHETHER 4*S2 IS A DERIVATION
// ==========================================================================
// If the whole i+j = 3 deficit lives in the super-W part, as
// `verify-cofactor-convolution.md` §3 argues P1's truncation does, then
//     1 - J = delta_tot / s,     delta_tot = 1 - T/(6 Nbar e3),  s = mm3/e3,
// with T = sum_{r in N} [C(a,2) b + a C(b,2)] the anchored total i+j=3 census,
// 6 Nbar e3 its CRT value, and mm3 = sum_{prod Q > W} 1/prod Q the missing mass
// that is the J denominator's second factor. Both T and mm3 are computed here
// exactly: T from the anchored a/b arrays, mm3 as e3 minus the sub-W triple sum,
// whose triple COUNT is a record figure (4,517,592 at @23).
function decomp(e) {
  const { W, A, N, qs, K } = e.L;
  const t0 = Date.now();
  const a = new Uint16Array(W), b = new Uint16Array(W);
  for (const q of qs) { for (let j = 0; j < W; j += q) a[j]++; for (let j = q - 2; j < W; j += q) b[j]++; }
  let T = 0, sm = 0, sm2 = 0;
  for (let r = 0; r < W; r++) {
    if (!A[r]) continue;
    const av = a[r], bv = b[r], m = av + bv;
    sm += m; sm2 += m * m;
    T += (av * (av - 1) / 2) * bv + av * (bv * (bv - 1) / 2);
  }
  // e3 and the sub-W triple sum
  let e1 = 0, e2 = 0, e3 = 0;
  { let E = [1, 0, 0, 0]; for (const q of qs) { const pq = 1 / q; for (let i = 3; i >= 1; i--) E[i] += E[i - 1] * pq; } e1 = E[1]; e2 = E[2]; e3 = E[3]; }
  let sub = 0, subCount = 0;
  for (let i = 0; i < K; i++) {
    const q1 = qs[i]; if (q1 * qs[i + 1] * qs[i + 2] >= W) break;
    for (let j = i + 1; j < K; j++) {
      const q12 = q1 * qs[j]; if (q12 * qs[j + 1] >= W) break;
      for (let k = j + 1; k < K; k++) {
        const P = q12 * qs[k]; if (P >= W) break;
        sub += 1 / P; subCount++;
      }
    }
  }
  const mm3 = e3 - sub;
  const crtTot = 6 * N * e3;
  const dtot = 1 - T / crtTot;
  const share = mm3 / e3;
  return { T, crtTot, dtot, e3, mm3, share, subCount, sub,
    meanM: sm / N, varM: sm2 / N - (sm / N) * (sm / N), secs: (Date.now() - t0) / 1000 };
}


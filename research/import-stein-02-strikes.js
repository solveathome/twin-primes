// so that the two files are speaking about the same object:
//   W  = 30 * prod_{7<=p<=x} p,  the primorial x#
//   N  = natal set = {r in [0,W) : r = 11 or 17 (mod 30), r != 0 and r != -2
//        (mod p) for every 7 <= p <= x};  Nbar = |N| = 2 * prod_{7<=p<=x}(p-2)
//   scour primes = {q prime : q > x and q^2 <= W}, K of them
//   a(r) = #{q | r},  b(r) = #{q | r+2}
//
// THE AGG SETUP. I = {(q,L), (q,R) : q scour}, X_{(q,L)} = 1{q | r} and
// X_{(q,R)} = 1{q | r+2} with r drawn uniformly from N, so p_alpha = 1/q and
// lambda = EW = 2 * sum_q 1/q. The neighbourhood is B_{(q,.)} = {(q,L),(q,R)}:
// the two orientations of one prime are exactly the pair the construction
// forces to be dependent, since a prime q > 2 cannot divide both r and r+2.
// That mutual exclusion is the whole of the forced scale
// F = prod_{q>x}(1 + 1/(q(q-2))) - 1 of `import-suen.md` §3.
//
// TWO OF THE THREE ARE CLOSED FORM AND EXACT:
//   b2 = sum_alpha sum_{alpha != beta in B_alpha} p_{alpha beta}
//      = sum_q [ P(q|r and q|r+2) + P(q|r+2 and q|r) ] = 0    EXACTLY
//   b1 = sum_alpha sum_{beta in B_alpha} p_alpha p_beta
//      = sum_q [ (1/q)(1/q) + (1/q)(1/q) ] * 2 = 4 * sum_q 1/q^2 = 4 S2
// and by AGG's own identity "when b3 = 0, b2 - b1 = E(W^2) - E(Z^2)" this is
// not a bound: the strike count a+b is under-dispersed against Poisson by
// exactly 4 S2, since a+b is a sum of independent Bernoulli(2/q) whose variance
// is lambda - 4 S2.
//
// b3 IS THE WHOLE QUESTION and it is what the pre-registered kill criterion
// turns on. b3 = sum_alpha E| E{X_alpha - p_alpha | sigma(X_beta : beta not in
// B_alpha)} |. The conditioning sigma-algebra is generated by the strike
// signature of r with q's own two entries deleted, so its cells are
//     cell(sigma, q) = {r in N : sig(r) \ {(q,L),(q,R)} = sigma},
// a union of at most three signature classes: sigma, sigma+(q,L), sigma+(q,R).
// Writing n(.) for class sizes,
//   Nbar * b3^{(q,L)} = sum_{sigma not containing q}
//                       | n(sigma+(q,L)) - (1/q)(n(sigma)+n(sigma+(q,L))+n(sigma+(q,R))) |
// and the cells with no q-sibling contribute (1/q) n(sigma) each, in closed
// form, because their total base count is Nbar - n_q minus the reached part.
// So b3 is computed EXACTLY here, not bounded: every cell with a q-sibling is
// enumerated (there are sum_q n_q = 2 S1 Nbar of the relevant r), and the rest
// is a closed form. The only inexactness is hash collision between distinct
// signatures, which is measured and reported.
//

// Separate the two effects in the localized gap.  See LOCALIZED-GAP.md §5.
// M(x, Y) at FIXED Y as x climbs isolates FOLD DAMAGE with no window growth.
// The Impact Lemma says the head [0,x^2) freezes, so once x > sqrt(Y) the
// sequence must go flat.  Between those two points is the whole recursion.

const N = 3e7;
const YS = [1e4, 1e5, 1e6, 1e7, 3e7];

function primesUpTo(n) {
  const s = new Uint8Array(n + 1); const out = [];
  for (let i = 2; i <= n; i++) if (!s[i]) { out.push(i); for (let j = i*i; j <= n; j += i) s[j] = 1; }
  return out;
}
const ladder = primesUpTo(6000);
const rough = new Uint8Array(N + 3).fill(1); rough[0] = 0;

function localized(Y) {
  let prev = -1, best = 0, count = 0;
  for (let r = 1; r < Math.min(Y + 8192, N); r++) {
    if (rough[r] && rough[r + 2]) {
      if (prev >= 0 && prev < Y) { const g = r - prev; if (g > best) best = g; }
      prev = r; count++;
      if (prev >= Y && best > 0) break;
    }
  }
  return { M: best, count };
}

const hist = YS.map(() => []);
console.log('x\t' + YS.map(Y => `M(x,${Y.toExponential(0)})`).join('\t'));
for (const x of ladder) {
  for (let j = x; j <= N + 2; j += x) rough[j] = 0;
  if (x < 3) continue;
  const row = YS.map((Y, i) => {
    if (x * x > Y * 4) return null;            // frozen well past sqrt(Y)
    const { M } = localized(Y); hist[i].push({ x, M }); return M;
  });
  if (row.some(v => v !== null))
    console.log(`${x}\t` + row.map(v => v === null ? '.' : v).join('\t\t'));
  if (x * x > 4 * YS[YS.length - 1]) break;
}

